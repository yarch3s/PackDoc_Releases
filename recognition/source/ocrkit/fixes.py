"""Правки прочитанной строки по смыслу поля: места, где знак нельзя надёжно прочитать по картинке, но можно
восстановить по тому, что в этом месте документа бывает.

Правил намеренно мало, каждое проверено замером (docs/LOGIC_ocr.md, раздел о точности) и не может испортить верное
чтение: то, что правило заменяет, в документах качества не встречается.

1. Римская цифра перед пунктом UW-NN. Пункты UW есть только в разделе VIII кодекса ASME (сосуды под давлением),
   а римскую VIII, набранную одним знаком, модели читают как V, VI или VII: «ASME VII UW-51» -> «ASME VIII UW-51».
2. Марки стали по ASTM A350 называются LF1, LF2, LF3 и так далее; марок «LP» нет, а жирную F модели иногда
   читают как P: «A350 LP2» -> «A350 LF2».
"""
from __future__ import annotations

import re

_ROMAN_UW = re.compile(r'(?:(?<![A-Za-z0-9])|(?<=ASME))V[IL1l|]{0,3}(\s*)(?=UW-\d)')
_A350_LF = re.compile(r'A350(\s*)LP(?=\d)')


def fix_line(text: str) -> str:
    """Правки одной строки текста. Длина текста может измениться на один-два знака."""
    if 'UW-' in text:
        text = _ROMAN_UW.sub(lambda m: 'VIII' + m.group(1), text)
    if 'A350' in text:
        text = _A350_LF.sub(lambda m: 'A350' + m.group(1) + 'LF', text)
    return text
